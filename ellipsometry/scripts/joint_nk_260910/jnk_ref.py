def n_si(wl):
    """Si complex index.  Outside 250-1450 nm this extrapolates - don't."""
    wl = np.asarray(wl, float)
    return (_si_n(wl) + 1j * np.maximum(_si_k(wl), 0.0)).astype(complex)


def n_ag_bulk(wl):
    """Bulk evaporated Ag (McPeak).  Reference only."""
    wl = np.asarray(wl, float)
    return (_ag_n(wl) + 1j * np.maximum(_ag_k(wl), 0.0)).astype(complex)


