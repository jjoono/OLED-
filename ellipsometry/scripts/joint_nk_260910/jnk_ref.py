def n_si_aspnes(wl):
    """Si, Aspnes & Studna 1983.  Valid 207-827 nm only."""
    wl = np.asarray(wl, float)
    return (_as_n(wl) + 1j * np.maximum(_as_k(wl), 0.0)).astype(complex)

def n_sio2(wl):
    """Fused silica, Malitson 1965."""
    lam = np.asarray(wl, float) / 1000.0
    n2 = (1 + 0.6961663 * lam**2 / (lam**2 - 0.0684043**2)
            + 0.4079426 * lam**2 / (lam**2 - 0.1162414**2)
            + 0.8974794 * lam**2 / (lam**2 - 9.896161**2))
    return np.sqrt(np.maximum(n2, 1.0)).astype(complex)


def n_air(wl):
    return np.ones(len(np.atleast_1d(wl)), complex)


